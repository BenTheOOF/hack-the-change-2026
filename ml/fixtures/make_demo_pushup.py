"""Write demo_pushup.json: a synthetic side-on push-up demo (4 reps, 10 fps).

The near arm (right side, facing the camera) is clearly visible. The far arm is hidden behind
the body, so it gets middling visibility and noisy, exaggerated guesses, as MediaPipe produces
for occluded limbs. Deterministic, so the fixture can be regenerated byte for byte.
Run: cd backend && uv run --group ml python ../ml/fixtures/make_demo_pushup.py
"""

import json
from math import acos, cos, pi, radians, sin, sqrt
from pathlib import Path

UPPER, FORE = 0.15, 0.17
WRIST = (0.30, 0.80)
ANKLE = (0.85, 0.80)
TOP, BOTTOM = 170.0, 80.0


class Lcg:
    def __init__(self, seed: int) -> None:
        self.seed = seed

    def __call__(self, scale: float) -> float:
        self.seed = (self.seed * 1103515245 + 12345) % 2**31
        return (self.seed / 2**31 - 0.5) * 2 * scale


def near_arm(elbow: float) -> dict[int, tuple[float, float]]:
    """Joint positions (x, y) of a side-on push-up with the given elbow angle, facing left."""
    d = sqrt(UPPER**2 + FORE**2 - 2 * UPPER * FORE * cos(radians(elbow)))
    shoulder = (WRIST[0], WRIST[1] - d)
    # Elbow sits behind the shoulder-wrist line, toward the feet.
    a = acos(max(-1.0, min(1.0, (UPPER**2 + d**2 - FORE**2) / (2 * UPPER * d))))
    elbow_pt = (shoulder[0] + UPPER * sin(a), shoulder[1] + UPPER * cos(a))
    hip = tuple(s + 0.45 * (k - s) for s, k in zip(shoulder, ANKLE))
    knee = tuple(s + 0.73 * (k - s) for s, k in zip(shoulder, ANKLE))
    return {0: (shoulder[0] - 0.08, shoulder[1] - 0.02), 12: shoulder, 14: elbow_pt, 16: WRIST,
            24: hip, 26: knee, 28: ANKLE, 32: (ANKLE[0] - 0.03, ANKLE[1] + 0.01)}


FAR = {12: 11, 14: 13, 16: 15, 24: 23, 26: 25, 28: 27, 32: 31}


def pushup_frame(elbow: float, t: float, noise: Lcg, mirror: bool = False, visibility: float = 0.95) -> dict:
    pts = [{"x": 0.5, "y": 0.5, "z": 0.0, "visibility": 0.2} for _ in range(33)]
    near = near_arm(elbow)
    for i, (x, y) in near.items():
        pts[i] = {"x": x, "y": y, "z": 0.0, "visibility": visibility}
    for n, f in FAR.items():
        x, y = near[n]
        # Hidden limb: small offset, middling visibility, and large jitter on the arm.
        jitter = 0.07 if n in (14, 16) else 0.01
        pts[f] = {"x": x + 0.01 + noise(jitter), "y": y - 0.01 + noise(jitter), "z": 0.0, "visibility": 0.65}
    if mirror:
        # Facing right: swap sides and flip horizontally.
        swapped = list(pts)
        for n, f in FAR.items():
            swapped[n], swapped[f] = pts[f], pts[n]
        pts = [{**p, "x": 1 - p["x"]} for p in swapped]
    for p in pts:
        p["x"], p["y"] = round(p["x"], 5), round(p["y"], 5)
    return {"t": t, "aspect_ratio": 1.33333, "points": pts}


def demo_frames(start_mid_rep: bool = False) -> list[dict]:
    noise, frames, t = Lcg(11), [], 0
    def add(angle: float) -> None:
        nonlocal t
        frames.append(pushup_frame(angle, t, noise))
        t += 100
    if start_mid_rep:  # the trim begins near the bottom of a rep
        for i in range(8):
            add(BOTTOM + (TOP - BOTTOM) * i / 8)
    for _ in range(10):
        add(TOP)
    for rep in range(4):
        for i in range(25):
            add(TOP - (TOP - BOTTOM) * 0.5 * (1 - cos(2 * pi * i / 24)))
        for _ in range(8 if rep < 3 else 10):
            add(TOP)
    return frames


def rep_stream(bottom: float = BOTTOM, ms: int = 2400, mirror: bool = False, seed: int = 5) -> list[dict]:
    """A patient rep with rest before and after, before segmentation."""
    noise, steps = Lcg(seed), ms // 100
    angles = [TOP] * 4 + [TOP - (TOP - bottom) * 0.5 * (1 - cos(2 * pi * i / steps)) for i in range(steps + 1)] + [TOP] * 5
    return [pushup_frame(a, i * 100, noise, mirror=mirror) for i, a in enumerate(angles)]


def main() -> None:
    here = Path(__file__).parent
    (here / "demo_pushup.json").write_text(json.dumps({"view": "side", "frames": demo_frames()}, separators=(",", ":")))
    cases = {
        "demo_mid_rep": demo_frames(start_mid_rep=True),
        "reps": {"full": rep_stream(), "mirrored": rep_stream(mirror=True), "shallow": rep_stream(bottom=130),
                 "fast": rep_stream(ms=800)},
    }
    (here / "pushup_cases.json").write_text(json.dumps(cases, separators=(",", ":")))
    print("wrote demo_pushup.json and pushup_cases.json")


if __name__ == "__main__":
    main()
