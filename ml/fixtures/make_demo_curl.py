"""Write demo_curl.json: a synthetic front-view demo of four two-arm elbow curls at 10 fps.

Deterministic (a small LCG adds jitter), so the fixture can be regenerated byte for byte.
Run: cd backend && uv run --group ml python ../ml/fixtures/make_demo_curl.py
"""

import json
from math import cos, pi, radians, sin
from pathlib import Path

REST, PEAK, REP_MS, GAP_MS, EDGE_MS, STEP_MS = 165.0, 50.0, 2400, 600, 1500, 100


def curl_frame(elbow: float, t: float, visibility: float = 0.9) -> dict:
    """One 33-point frame standing still with both elbows at the given angle."""
    pts = [{"x": 0.5, "y": 0.12, "z": 0.0, "visibility": visibility} for _ in range(33)]

    def put(i: int, x: float, y: float) -> None:
        pts[i] = {"x": round(x, 5), "y": round(y, 5), "z": 0.0, "visibility": visibility}

    for i, (x, y) in {11: (0.42, 0.30), 12: (0.58, 0.30), 13: (0.42, 0.45), 14: (0.58, 0.45),
                      23: (0.45, 0.55), 24: (0.55, 0.55), 25: (0.45, 0.75), 26: (0.55, 0.75),
                      27: (0.45, 0.95), 28: (0.55, 0.95)}.items():
        put(i, x, y)
    a = radians(elbow)
    put(15, 0.42 + 0.15 * sin(a), 0.45 - 0.15 * cos(a))
    put(16, 0.58 - 0.15 * sin(a), 0.45 - 0.15 * cos(a))
    return {"t": t, "points": pts}


def main() -> None:
    seed = 7

    def jitter() -> float:
        nonlocal seed
        seed = (seed * 1103515245 + 12345) % 2**31
        return (seed / 2**31 - 0.5) * 3.0

    frames, t = [], 0
    def add(angle: float) -> None:
        nonlocal t
        frames.append(curl_frame(angle + jitter(), t))
        t += STEP_MS
    for _ in range(EDGE_MS // STEP_MS):
        add(REST)
    for rep in range(4):
        for i in range(REP_MS // STEP_MS + 1):
            add(REST - (REST - PEAK) * 0.5 * (1 - cos(2 * pi * i * STEP_MS / REP_MS)))
        for _ in range((GAP_MS if rep < 3 else EDGE_MS) // STEP_MS):
            add(REST)
    out = Path(__file__).with_name("demo_curl.json")
    out.write_text(json.dumps({"view": "front", "frames": frames}, separators=(",", ":")))
    print(f"wrote {len(frames)} frames to {out}")


if __name__ == "__main__":
    main()
